<?php

namespace App\Http\Controllers;

use App\Models\Category;
use App\Models\Material;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Validation\Rule;
use Illuminate\View\View;

class MaterialController extends Controller
{
    // Show materials and calculate their current balances.
    public function index(): View
    {
        $materials = Material::with('category')
            ->withSum('transactions', 'quantity')
            ->orderByDesc('id')
            ->paginate(10);

        return view('materials.index', compact('materials'));
    }

    // Show the form to create a material.
    public function create(): View
    {
        $categories = Category::orderBy('name')->get();

        return view('materials.create', compact('categories'));
    }

    // Validate and save a material; its ID is generated by the database.
    public function store(Request $request): RedirectResponse
    {
        $validated = $request->validate([
            'category_id' => ['required', 'integer', 'exists:categories,id'],
            'name' => [
                'required', 'string', 'max:150',
                'regex:/^(?=.*[A-Za-z0-9])[A-Za-z0-9 _-]+$/',
                Rule::unique('materials', 'name')->where(
                    fn ($query) => $query->where('category_id', $request->input('category_id'))
                ),
            ],
            'opening_balance' => ['required', 'numeric', 'regex:/^-?\d+(?:\.\d{1,2})?$/'],
        ], [
            'name.regex' => 'Material name may contain letters, numbers, spaces, hyphens and underscores only.',
            'opening_balance.regex' => 'Opening balance must have no more than 2 decimal places.',
        ]);

        Material::create($validated);

        return redirect()->route('materials.index')->with('success', 'Material added successfully.');
    }

    // Show the edit form for a material's basic details only.
    public function edit(Material $material): View
    {
        $categories = Category::orderBy('name')->get();

        return view('materials.edit', compact('material', 'categories'));
    }

    // Update category, name and opening balance; transaction history is unchanged.
    public function update(Request $request, Material $material): RedirectResponse
    {
        $validated = $request->validate([
            'category_id' => ['required', 'integer', 'exists:categories,id'],
            'name' => [
                'required', 'string', 'max:150',
                'regex:/^(?=.*[A-Za-z0-9])[A-Za-z0-9 _-]+$/',
                Rule::unique('materials', 'name')
                    ->where(fn ($query) => $query->where('category_id', $request->input('category_id')))
                    ->ignore($material->id),
            ],
            'opening_balance' => ['required', 'numeric', 'regex:/^-?\d+(?:\.\d{1,2})?$/'],
        ], [
            'name.regex' => 'Material name may contain letters, numbers, spaces, hyphens and underscores only.',
            'opening_balance.regex' => 'Opening balance must have no more than 2 decimal places.',
        ]);

        $material->update($validated);

        return redirect()->route('materials.index')->with('success', 'Material updated successfully.');
    }

    // Soft-delete a material; its transaction rows remain in the database.
    public function destroy(Material $material): RedirectResponse
    {
        $material->delete();

        return redirect()->route('materials.index')->with('success', 'Material moved to deleted records.');
    }

    // AJAX endpoint used to populate the material dropdown by category.
    public function byCategory(Category $category): JsonResponse
    {
        return response()->json(
            $category->materials()->orderBy('name')->get(['id', 'name'])
        );
    }
}
